import { formatNumber } from "./numbers.mjs";
// How the suite's tests distribute across operations, from the suite's manifest.
//
// The methodology explains why coverage is weighted by test count rather than by
// a count of features, and it explains it with the extremes: one operation
// carrying a hundred-odd tests beside three carrying a couple each. Those counts
// were typed in, and the suite grows - the same page says so two sections later -
// so `putItem` had gained fourteen tests since anyone last read the sentence.
//
// registry/suite-manifest.json is the same artefact the ground-truth coverage
// gate reads, committed alongside the tests and regenerated by `npm run
// suite:manifest`. Read off disk rather than fetched: it moves only when the
// tests move, and both are in this repository.

import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const MANIFEST = join(dirname(fileURLToPath(import.meta.url)), "..", "..", "registry", "suite-manifest.json");

// "tests/tier1/putItem/basic.test.ts::…" -> "putItem". The directory under the
// tier is the operation, which is how the suite has always been laid out and
// what scripts/lib/identity.mjs joins on.
const operationOf = (identity) => identity.split("/")[2] ?? null;

const NUMBER_WORDS = ["zero", "one", "two", "three", "four", "five", "six", "seven", "eight", "nine", "ten"];

/** A count in the page's voice: small ones in words, the rest in digits. */
export const countWord = (n) => (n != null && n < NUMBER_WORDS.length ? NUMBER_WORDS[n] : n == null ? String(n) : formatNumber(n));

const UNAVAILABLE = { available: false, size: null, byOperation: {} };

/** Tests per operation, plus the suite size, from a parsed manifest. */
export function shapeOf(manifest) {
  const identities = Array.isArray(manifest?.tests) ? manifest.tests : [];
  if (!identities.length) return UNAVAILABLE;

  const byOperation = {};
  for (const id of identities) {
    const op = operationOf(id);
    if (op) byOperation[op] = (byOperation[op] ?? 0) + 1;
  }
  return { available: true, size: manifest.count ?? identities.length, byOperation };
}

/**
 * The same, read off disk.
 *
 * Never throws: a checkout without the manifest renders the sentence's clause
 * away rather than failing the build, the same way the region overlay degrades.
 */
export function buildSuiteShape(path = MANIFEST) {
  try {
    return shapeOf(JSON.parse(readFileSync(path, "utf8")));
  } catch {
    return UNAVAILABLE;
  }
}

/**
 * "two each", or "two, two and three" when they differ.
 *
 * The sentence names three lightly-tested operations and says what they carry.
 * Written as a literal it claimed they were equal, which is true today and is
 * exactly the kind of thing that stops being true without anyone noticing.
 */
export function carriedEach(shape, names = []) {
  const counts = names.map((n) => shape?.byOperation?.[n]).filter((n) => n != null);
  if (counts.length !== names.length || !counts.length) return "";
  const unique = [...new Set(counts)];
  if (unique.length === 1) return `${countWord(unique[0])} each`;
  const words = counts.map(countWord);
  return `${words.slice(0, -1).join(", ")} and ${words[words.length - 1]}`;
}
